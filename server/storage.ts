import { del, get, list, put } from '@vercel/blob'
import express, { type RequestHandler } from 'express'
import { randomBytes } from 'node:crypto'
import { mkdir, readdir, readFile, rename, stat, unlink, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { Readable } from 'node:stream'

/** An error whose message is safe to show to the admin. */
export class HttpError extends Error {
  constructor(
    readonly status: number,
    message: string,
  ) {
    super(message)
  }
}

export type ImageType = 'jpg' | 'png' | 'webp' | 'gif'

export const IMAGE_CONTENT_TYPES: Record<ImageType, string> = {
  jpg: 'image/jpeg',
  png: 'image/png',
  webp: 'image/webp',
  gif: 'image/gif',
}

// Upload names are always generated by the server: 32 hex chars + a known extension
const UPLOAD_NAME = /^[a-f0-9]{32}\.(jpg|png|webp|gif)$/

// Uploads that are no longer used are kept this long, because an admin may have
// uploaded them for changes that are not saved yet.
const UNUSED_UPLOAD_GRACE_MS = 24 * 60 * 60 * 1000

export interface Storage {
  readonly description: string
  /** The saved content (parsed JSON), or null when nothing has been saved yet. */
  readContent(): Promise<unknown>
  writeContent(json: string): Promise<void>
  writeUpload(name: string, data: Buffer, type: ImageType): Promise<void>
  /** Serves GET /uploads/<name>. */
  serveUploads: RequestHandler
  /** Deletes uploads not in `used` (a set of `/uploads/<name>` paths) and older than a day. */
  removeUnusedUploads(used: Set<string>): Promise<void>
}

// ---------- local disk (development, or a server with a persistent disk) ----------

function localStorage(dir: string): Storage {
  const contentFile = path.join(dir, 'content.json')
  const uploadDir = path.join(dir, 'uploads')

  async function writeAtomic(file: string, data: string | Buffer): Promise<void> {
    const tmp = `${file}.${randomBytes(6).toString('hex')}.tmp`
    await writeFile(tmp, data)
    await rename(tmp, file)
  }

  return {
    description: `local disk (${dir})`,
    async readContent() {
      try {
        return JSON.parse(await readFile(contentFile, 'utf8'))
      } catch {
        return null
      }
    },
    writeContent: (json) => writeAtomic(contentFile, json),
    async writeUpload(name, data) {
      await mkdir(uploadDir, { recursive: true })
      await writeAtomic(path.join(uploadDir, name), data)
    },
    // Random file names never change, so they can be cached forever
    serveUploads: express.static(uploadDir, { dotfiles: 'deny', index: false, immutable: true, maxAge: '1y', fallthrough: false }),
    async removeUnusedUploads(used) {
      const files = await readdir(uploadDir).catch(() => [] as string[])
      const cutoff = Date.now() - UNUSED_UPLOAD_GRACE_MS
      for (const file of files) {
        if (used.has(`/uploads/${file}`)) continue
        const full = path.join(uploadDir, file)
        const info = await stat(full).catch(() => null)
        if (info && info.mtimeMs < cutoff) await unlink(full).catch(() => {})
      }
    },
  }
}

// ---------- Vercel Blob (serverless hosting, where the disk is not kept) ----------

function blobStorage(access: 'public' | 'private'): Storage {
  const CONTENT = 'content.json'

  return {
    description: `Vercel Blob (${access})`,
    async readContent() {
      // useCache: false reads straight from storage, so a save is visible immediately
      const result = await get(CONTENT, { access, useCache: false })
      if (!result || result.statusCode !== 200) return null
      return JSON.parse(await new Response(result.stream).text())
    },
    async writeContent(json) {
      await put(CONTENT, json, { access, addRandomSuffix: false, allowOverwrite: true, contentType: 'application/json', cacheControlMaxAge: 60 })
    },
    async writeUpload(name, data, type) {
      await put(`uploads/${name}`, data, { access, addRandomSuffix: false, contentType: IMAGE_CONTENT_TYPES[type] })
    },
    async serveUploads(req, res, next) {
      try {
        const name = req.path.slice(1)
        const match = UPLOAD_NAME.exec(name)
        if (req.method !== 'GET' && req.method !== 'HEAD') throw new HttpError(405, 'Niet toegestaan')
        if (!match) throw new HttpError(404, 'Niet gevonden')
        const result = await get(`uploads/${name}`, { access })
        if (!result || result.statusCode !== 200) throw new HttpError(404, 'Niet gevonden')
        res.set({
          'Content-Type': IMAGE_CONTENT_TYPES[match[1] as ImageType],
          'Content-Length': String(result.blob.size),
          // Random names never change: let browsers and Vercel's CDN keep them
          'Cache-Control': 'public, max-age=31536000, immutable',
        })
        if (req.method === 'HEAD') {
          res.end()
          await result.stream.cancel()
          return
        }
        Readable.fromWeb(result.stream as import('node:stream/web').ReadableStream).pipe(res)
      } catch (err) {
        next(err)
      }
    },
    async removeUnusedUploads(used) {
      const cutoff = Date.now() - UNUSED_UPLOAD_GRACE_MS
      const unused: string[] = []
      let cursor: string | undefined
      do {
        const page = await list({ prefix: 'uploads/', cursor })
        for (const blob of page.blobs) {
          if (!used.has(`/${blob.pathname}`) && blob.uploadedAt.getTime() < cutoff) unused.push(blob.url)
        }
        cursor = page.hasMore ? page.cursor : undefined
      } while (cursor)
      if (unused.length > 0) await del(unused)
    },
  }
}

// ---------- not configured (deployed to Vercel without a Blob store) ----------

function missingStorage(): Storage {
  const fail = async (): Promise<never> => {
    throw new HttpError(503, 'Opslag is niet ingesteld: koppel een Vercel Blob store aan dit project')
  }
  return {
    description: 'none (BLOB_READ_WRITE_TOKEN or BLOB_STORE_ID is missing)',
    readContent: async () => null,
    writeContent: fail,
    writeUpload: fail,
    serveUploads: (_req, _res, next) => next(new HttpError(404, 'Niet gevonden')),
    removeUnusedUploads: async () => {},
  }
}

export function createStorage(localDir: string): Storage {
  // A Blob store connected to the Vercel project sets BLOB_READ_WRITE_TOKEN (token auth)
  // or BLOB_STORE_ID (OIDC auth)
  if (process.env.BLOB_READ_WRITE_TOKEN || process.env.BLOB_STORE_ID) return blobStorage(process.env.BLOB_ACCESS === 'public' ? 'public' : 'private')
  if (process.env.VERCEL) return missingStorage()
  return localStorage(localDir)
}
